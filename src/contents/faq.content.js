export function getPageFaqData(pathname = '/') {
  const clean = String(pathname || '/').split('?')[0].replace(/\/+$/, '') || '/';

  // Exact or prefix matches
  if (pageFaqCatalog[clean]) {
    return {
      sectionTitle: pageFaqCatalog[clean].sectionTitle,
      faqs: pageFaqCatalog[clean].faqs,
      sidebar: faqContent.sidebar,
      bottom: faqContent.bottom
    };
  }

  // Route alias matches
  if (clean.startsWith('/founder') || clean.startsWith('/research')) {
    return { ...pageFaqCatalog['/founder'], sidebar: faqContent.sidebar, bottom: faqContent.bottom };
  }
  if (clean.startsWith('/about')) {
    return { ...pageFaqCatalog['/about'], sidebar: faqContent.sidebar, bottom: faqContent.bottom };
  }
  if (clean.startsWith('/workshops') || clean.startsWith('/positive-workshops') || clean.startsWith('/events')) {
    return { ...pageFaqCatalog['/positive-workshops'], sidebar: faqContent.sidebar, bottom: faqContent.bottom };
  }
  if (clean.startsWith('/mentoring') || clean.startsWith('/positive-mentoring')) {
    return { ...pageFaqCatalog['/positive-mentoring'], sidebar: faqContent.sidebar, bottom: faqContent.bottom };
  }
  if (clean.startsWith('/mindgym') || clean.startsWith('/positive-mindgym-app')) {
    return { ...pageFaqCatalog['/mindgym'], sidebar: faqContent.sidebar, bottom: faqContent.bottom };
  }
  if (clean.startsWith('/shop') || clean.startsWith('/product-details') || clean.startsWith('/cart')) {
    return { ...pageFaqCatalog['/shop'], sidebar: faqContent.sidebar, bottom: faqContent.bottom };
  }
  if (clean.startsWith('/contact')) {
    return { ...pageFaqCatalog['/contact'], sidebar: faqContent.sidebar, bottom: faqContent.bottom };
  }

  return {
    sectionTitle: faqContent.sectionTitle,
    faqs: defaultFaqs,
    sidebar: faqContent.sidebar,
    bottom: faqContent.bottom
  };
}

