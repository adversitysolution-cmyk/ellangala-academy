/**
 * Filter and rank books based on:
 * 1. User's chosen profile topics (e.g. from registration or community preferences)
 * 2. Active feed category / topic selected in sidebar
 */
export function getRecommendedBooks({ userTopics = [], selectedCategory = 'all', limit = 3 } = {}) {
  const activeTopics = (Array.isArray(userTopics) ? userTopics : [])
    .map(t => String(t).trim().toLowerCase())
    .filter(Boolean);

  const activeCategory = selectedCategory && selectedCategory !== 'all'
    ? String(selectedCategory).trim().toLowerCase()
    : null;

  const scored = COMMUNITY_BOOKS.map(book => {
    let score = 0;
    let matchedTag = null;
    const bookTopicsLower = book.topics.map(t => t.toLowerCase());

    // Category filter in sidebar gives strong intent match
    if (activeCategory) {
      const catMatch = bookTopicsLower.some(t => t === activeCategory || t.includes(activeCategory) || activeCategory.includes(t));
      if (catMatch) {
        score += 30;
        matchedTag = book.badge;
      }
    }

    // Match each of the user's selected interest topics
    for (const ut of activeTopics) {
      const match = book.topics.find(t => {
        const tl = t.toLowerCase();
        return tl === ut || tl.includes(ut) || ut.includes(tl);
      });
      if (match) {
        score += 15;
        if (!matchedTag) {
          matchedTag = book.badge;
        }
      }
    }

    return {
      ...book,
      score,
      matchedTag: matchedTag || book.badge
    };
  });

  // Sort descending by match score, then ascending by editorial priority
  scored.sort((a, b) => {
    if (b.score !== a.score) return b.score - a.score;
    return a.priority - b.priority;
  });

  return scored.slice(0, limit);
}
